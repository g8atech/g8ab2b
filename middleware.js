export default function middleware(request) {
  const url = new URL(request.url);
  const rules = RULES[url.hostname.toLowerCase()];
  if (!rules) return; // dominio principale: nessun intervento
  let path = url.pathname;
  try { path = decodeURIComponent(path); } catch {}
  for (const [pattern, dest] of rules) {
    const m = new RegExp(pattern).exec(path);
    if (m) {
      const target = dest.replace('$1', m[1] ?? '').replace(/([^:])\/\/+/g, '$1/');
      return Response.redirect(target, 301);
    }
  }
}
